def _ensure_pose_context(arm_obj):
    """``bpy.ops.pose.*`` needs "active object = armature + Pose mode". Returns (previous active object, previous mode)."""
    view_layer = bpy.context.view_layer
    previous = None
    previous_mode = arm_obj.mode
    try:
        previous = view_layer.objects.active if view_layer is not None else None
        if previous is not arm_obj:
            for obj in list(bpy.context.selected_objects):
                obj.select_set(False)
            arm_obj.select_set(True)
            view_layer.objects.active = arm_obj
        if arm_obj.mode != "POSE":
            bpy.ops.object.mode_set(mode="POSE")
    except Exception as exc:  # noqa: BLE001
        utils.warn("Failed to switch to Pose mode (needed for the IK snap): %s" % exc)
    return previous, previous_mode


def _update_view() -> None:
    """Make the dependency graph recompute (IK solves / constraint results only take effect through it)."""
    view_layer = bpy.context.view_layer
    if view_layer is not None:
        view_layer.update()


def pole_enabled(arm_obj, spec: dict) -> bool:
    """Whether this limb currently uses the "pole target" (the ``pole_vector`` switch on Rigify's panel)."""
    prop = spec.get("pole_prop") or "pole_vector"
    pb = arm_obj.pose.bones.get(spec.get("prop_bone") or "")
    try:
        return bool(pb is not None and prop in pb.keys() and pb[prop])
    except (TypeError, ValueError):  # noqa: BLE001
        return False


def _perpendicular(vec):
    """Rigify ``perpendicular_vector``: pick any direction perpendicular to ``vec`` (not guaranteed to be normalised)."""
    other = Vector((1.0, 0.0, 0.0)) if abs(vec[0]) < abs(vec[1]) else Vector((0.0, 1.0, 0.0))
    return vec.cross(other)


def _rotation_difference(mat1, mat2) -> float:
    """Rigify ``rotation_difference``: the **signed** angle (radians) of the shortest path between two rotations."""
    q1, q2 = mat1.to_quaternion(), mat2.to_quaternion()
    angle = math.acos(min(1.0, max(-1.0, q1.dot(q2)))) * 2.0
    if angle > math.pi:
        angle = -angle + 2.0 * math.pi
    return angle


def place_pole(arm_obj, spec: dict, match_matrix) -> bool:
    """Place the pole target (``*_ik_target``) into the plane of the FK chain.

    The bend plane of the IK chain is decided by the pole target: if it is not placed (left at its previous position), the knee / elbow of the new pose
    points the wrong way - in testing the right leg was off by 0.21 m / 26 degrees, and after placing it correctly within 1.4 degrees. The algorithm is copied from Rigify's
    ``match_pole_target``: take the line "chain root -> chain end", pick a perpendicular out from its middle and put the pole there; then see how much the root orientation
    differs from FK, rotate along the line once in each direction and keep the side that is closer to FK.

    Returns whether it was actually placed. ``match_matrix`` is the pose matrix of the first FK chain bone.
    """
    ik_names = spec.get("ik_bones") or []
    ctrl_names = spec.get("ctrl_bones") or []
    if len(ik_names) < 2 or len(ctrl_names) < 2:
        return False
    ik_first = arm_obj.pose.bones.get(ik_names[0])
    ik_last = arm_obj.pose.bones.get(ik_names[1])
    pole = arm_obj.pose.bones.get(ctrl_names[1])
    if ik_first is None or ik_last is None or pole is None:
        return False

    a = ik_first.matrix.to_translation()
    b = ik_last.tail.copy()          # == Rigify's ik_last.matrix.translation + ik_last.vector
    ikv = b - a
    if ikv.length < 1e-6:
        return False
    offset = _perpendicular(ikv).normalized() * (ik_first.bone.length + ik_last.bone.length)

    def set_pole(vector) -> None:
        matrix = pole.matrix.copy()
        matrix.translation = a + (ikv / 2.0) + vector
        pole.matrix = matrix
        _update_view()

    set_pole(offset)
    angle = _rotation_difference(ik_first.matrix, match_matrix)
    plus = Matrix.Rotation(angle, 4, ikv) @ offset
    set_pole(plus)
    angle_plus = _rotation_difference(ik_first.matrix, match_matrix)
    minus = Matrix.Rotation(-angle, 4, ikv) @ offset
    set_pole(minus)
    angle_minus = _rotation_difference(ik_first.matrix, match_matrix)
    if angle_plus < angle_minus:
        set_pole(plus)
    return True


def snap_fk_to_ik(arm_obj, spec: dict, report: dict = None) -> bool:
    """Call Rigify's own "IK->FK" snap: move the pose of the FK chain onto the IK controls.

    It is the same operator as the button on Rigify's panel; the pole / stretch / heel-and-foot maths are all done by
    Rigify itself, so we do not have to solve IK by hand.
    """
    rid = rig_id(arm_obj)
    op_name = "rigify_limb_ik2fk_%s" % rid
    op = getattr(bpy.ops.pose, op_name, None)
    if op is None:
        if report is not None:
            report.setdefault("warnings", []).append(
                "Operator %s not found (%s is not a Rigify-generated armature?)" % (op_name, arm_obj.name))
        return False
    kwargs = {
        "prop_bone": spec["prop_bone"],
        "pole_prop": spec.get("pole_prop") or "pole_vector",
        "fk_bones": json.dumps(spec["fk_bones"]),
        "ik_bones": json.dumps(spec["ik_bones"]),
        "ctrl_bones": json.dumps(spec["ctrl_bones"]),
        "tail_bones": json.dumps(spec.get("tail_bones") or []),
        "extra_ctrls": json.dumps(spec.get("extra_ctrls") or []),
    }
    try:
        result = op(**kwargs)
    except Exception as exc:  # noqa: BLE001
        if report is not None:
            report.setdefault("warnings", []).append(
                "IK snap failed (%s): %s" % (spec["fk_bones"][0], exc))
        return False
    if "FINISHED" not in result and report is not None:
        report.setdefault("warnings", []).append(
            "IK snap did not finish (%s): %s" % (spec["fk_bones"][0], result))
    return "FINISHED" in result


def snap_limbs(arm_obj, specs: dict, report: dict = None) -> list[str]:
    """Run the FK->IK snap for several limbs; returns the first FK chain bone names that were moved over successfully."""
    if not specs:
        return []
    previous, previous_mode = _ensure_pose_context(arm_obj)
    done: list[str] = []
    try:
        for spec in specs.values():
            if snap_fk_to_ik(arm_obj, spec, report):
                done.append(spec["fk_bones"][0])
            view_layer = bpy.context.view_layer
            if view_layer is not None:
                view_layer.update()
    finally:
        if previous_mode != "POSE":
            try:
                bpy.ops.object.mode_set(mode=previous_mode)
            except Exception:  # noqa: BLE001
                pass
        if previous is not None and previous is not arm_obj:
            try:
                arm_obj.select_set(False)
                previous.select_set(True)
                bpy.context.view_layer.objects.active = previous
            except Exception:  # noqa: BLE001
                pass
    return done


