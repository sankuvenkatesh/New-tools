def _scan_tracked_armatures() -> list:
    out = []
    for obj in bpy.data.objects:
        if obj.type != "ARMATURE":
            continue
        try:
            if not obj.data.get("rig_id"):
                continue
            if not any("IK_FK" in bone.keys() for bone in obj.pose.bones
                       if bone.name.endswith(("_parent.L", "_parent.R"))):
                continue
        except Exception:  # noqa: BLE001
            continue
        out.append(obj)
    return out


def _tracked_armatures() -> list:
    """Cached: the handler is called every frame, so do not scan the whole scene object table each time."""
    count = len(bpy.data.objects)
    if _CANDIDATES["key"] != count:
        _CANDIDATES["key"] = count
        _CANDIDATES["list"] = _scan_tracked_armatures()
    alive = []
    for obj in _CANDIDATES["list"]:
        try:
            _ = obj.name          # accessing a deleted object raises ReferenceError
        except Exception:  # noqa: BLE001
            continue
        alive.append(obj)
    return alive


def _on_depsgraph_update(_scene, _depsgraph) -> None:
    """After the user drags Rigify's IK-FK slider by hand, try to sync the controller visibility.

    Note: ``IK_FK`` is a custom property on the PoseBone, and changing it does **not** trigger a depsgraph callback,
    so the check can only piggy-back on other updates (rotating the view / selecting bones / changing other properties ...);
    the "Sync Control Display" button in the N panel is kept as a fallback.
    """
    if _WATCH_BUSY[0]:
        return
    _WATCH_BUSY[0] = True
    try:
        for arm_obj in _tracked_armatures():
            specs = limb_specs(arm_obj)
            if not specs:
                continue
            modes = limb_modes(arm_obj, specs)
            if _WATCH_MEMO.get(arm_obj.name) == modes:
                continue
            _WATCH_MEMO[arm_obj.name] = modes
            sync_visibility(arm_obj, None, specs)
    except Exception:  # noqa: BLE001  an exception must never escape from a callback
        pass
    finally:
        _WATCH_BUSY[0] = False


def watcher_installed() -> bool:
    return _on_depsgraph_update in bpy.app.handlers.depsgraph_update_post


def ensure_watcher() -> None:
    """Install the automatic sync callback (when the add-on registers, and again after loading a new file (which clears the handlers))."""
    if not watcher_installed():
        bpy.app.handlers.depsgraph_update_post.append(_on_depsgraph_update)


def remove_watcher() -> None:
    if watcher_installed():
        bpy.app.handlers.depsgraph_update_post.remove(_on_depsgraph_update)
    _WATCH_MEMO.clear()

