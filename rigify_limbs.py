"""Rigify limb IK controller bridge (Rigify arms/thighs go through IK by default).

Background (verified with Blender 5.2 + the built-in rigify):
  * When a rig is generated, the ``IK_FK`` custom property on ``upper_arm_parent.L`` / ``thigh_parent.R``
    defaults to 0, i.e. **IK mode**;
  * In IK mode the deform bones follow the IK controls such as ``hand_ik`` / ``foot_ik``, so writing rotations
    straight to the ``*_fk`` bones does not change the deformation, and users think "the controls are broken";
  * Rigify's own "IK->FK (hand.L)" button is essentially
    ``pose.rigify_limb_ik2fk_<rig_id>`` (``RigifyLimbIk2FkBase.apply_frame_state``):
    it reads the pose matrices of the FK chain and computes the transforms of the IK controls.
    In testing, after moving the FK pose over and switching IK_FK back to 0, the position error of every DEF bone was 0.000000 m,
    and fingers / toes followed as well.

So the order in which the add-on writes the pose is:

* **IK mode (default)**: write the pose straight into the IK controls using the algorithm above - apply the **world delta**
  (position + rotation) of every FK chain bone to the matching control (``hand_ik`` / ``foot_ik`` are themselves the end of the IK chain;
  Rigify attaches them to the chain with a MCH bone carrying ``COPY_LOCATION``), and for the chain root ``upper_arm_ik`` / ``thigh_ik``
  search the twist around its own axis (the bend plane of the IK chain) following Rigify's
  ``correct_rotation``; if the pole target (``pole_vector``) is enabled,
  :func:`place_pole` puts ``*_ik_target`` into the plane of the FK chain; the FK chain is written as well (it is hidden in IK mode,
  so the pose is not lost when the user drags the slider back to FK, and the direct write needs it as the source of the deltas). After writing,
  the result is checked against the ``DEF-*`` deform bones (joint position 2 cm / direction 10 degrees; tails are not compared, because DEF bones driven by IK
  get lengthened by stretch), and limbs that do not match automatically fall back to the old path below, so the worst case is only
  "the direct write did not succeed", never a wrong pose. **No FK switch, no snap**;
* **Fallback path (old behaviour)**: switch to FK -> write the FK rotations -> call Rigify's own "IK->FK" snap to align the IK controls
  (the pole / stretch / heel maths are all done by Rigify) -> stay on IK or FK.

When switching to FK, the bone collection holding the IK controls is hidden by default (and vice versa); otherwise the user slides to FK,
sees the controls not moving, and thinks something is a bug.
"""
from __future__ import annotations

import ast
import json
import math
import re

import bpy
from mathutils import Matrix, Vector

from . import utils

MODE_IK = "IK"
MODE_FK = "FK"
MODES = (MODE_IK, MODE_FK)

_JSON_KEYS = ("fk_bones", "ik_bones", "ctrl_bones", "tail_bones", "extra_ctrls")
_STR_KEYS = ("prop_bone", "pole_prop")

# Chain names of the standard limbs (fallback when the generation script was deleted; only used when the bones really exist)
_DEFAULT_CHAINS = {
    "upper_arm": {"fk": ("upper_arm_fk.{s}", "forearm_fk.{s}", "hand_fk.{s}"),
                  "ik": ("upper_arm_ik.{s}", "MCH-forearm_ik.{s}",
                         "MCH-upper_arm_ik_target.{s}"),
                  "ctrl": ("upper_arm_ik.{s}", "upper_arm_ik_target.{s}", "hand_ik.{s}"),
                  "tail": (), "extra": (), "parent": "upper_arm_parent.{s}",
                  "kind": "Arm"},
    "thigh": {"fk": ("thigh_fk.{s}", "shin_fk.{s}", "foot_fk.{s}", "toe_fk.{s}"),
              "ik": ("thigh_ik.{s}", "MCH-shin_ik.{s}", "MCH-thigh_ik_target.{s}"),
              "ctrl": ("thigh_ik.{s}", "thigh_ik_target.{s}", "foot_ik.{s}"),
              "tail": ("toe_ik.{s}",),
              "extra": ("foot_heel_ik.{s}", "foot_spin_ik.{s}"),
              "parent": "thigh_parent.{s}", "kind": "Leg"},
}

_SPEC_CACHE: dict[tuple[str, str], dict] = {}


def rig_id(arm_obj) -> str:
    """The rig_id Rigify stores on the armature data of a generated rig (empty string for non-generated armatures)."""
    if arm_obj is None or getattr(arm_obj, "type", "") != "ARMATURE":
        return ""
    try:
        return str(arm_obj.data.get("rig_id") or "")
    except Exception:  # noqa: BLE001
        return ""


def _generated_script(rid: str) -> str:
    """Find the UI script generated by Rigify in all text blocks (it carries the limb ik2fk operator properties)."""
    needle = "rigify_limb_ik2fk_%s" % rid
    for text in bpy.data.texts:
        try:
            body = text.as_string()
        except Exception:  # noqa: BLE001
            continue
        if needle in body:
            return body
    return ""


def _parse_operator_props(body: str, op_name: str) -> list[dict]:
    """Parse the ``props.X = ...`` lines of the generated script into one property dict per operator.

    Note: other operators (e.g. the generic_snap snapshot of "FK->IK") also have same-named properties such as
    ``props.ctrl_bones``, so **every ``.operator(=`` line must end the block**, keeping only those whose name matches exactly,
    otherwise properties of other blocks get merged in (and the merged result would point to the opposite limb).
    """
    found: list[dict] = []
    current: dict | None = None
    quoted = "'%s'" % op_name
    for line in body.splitlines():
        line = line.strip()
        if ".operator(" in line:
            current = {} if quoted in line else None
            if current is not None:
                found.append(current)
            continue
        match = re.match(r"props\.(\w+)\s*=\s*(.+)$", line)
        if match and current is not None:
            raw = match.group(2).strip()
            try:
                current[match.group(1)] = ast.literal_eval(raw)
            except (ValueError, SyntaxError):
                current[match.group(1)] = raw.strip("'\"")
    return found



def _spec_from_raw(raw: dict, arm_obj) -> dict | None:
    """Property dict -> spec dict (returns None if a bone does not exist)."""
    spec: dict = {}
    for key, value in raw.items():
        if key in _JSON_KEYS:
            if isinstance(value, str):
                try:
                    spec[key] = list(json.loads(value))
                except ValueError:
                    spec[key] = []
            else:
                spec[key] = list(value or [])
        elif key in _STR_KEYS:
            spec[key] = str(value)
    for key in _JSON_KEYS:
        spec.setdefault(key, [])
    prop_bone = spec.get("prop_bone") or ""
    bones = spec.get("fk_bones") or []
    ik_bones = spec.get("ik_bones") or []
    ctrl_bones = spec.get("ctrl_bones") or []
    tail_bones = spec.get("tail_bones") or []
    extra_ctrls = spec.get("extra_ctrls") or []
    if not prop_bone or not bones or not ctrl_bones:
        return None
    # Rigify's own assertions: fk = ik + tail; control bones and IK result bones correspond one to one.
    # These two checks throw away blocks whose properties were polluted by another block.
    if len(bones) != len(ik_bones) + len(tail_bones) or len(ctrl_bones) != len(ik_bones):
        return None
    pb = arm_obj.pose.bones.get(prop_bone)
    if pb is None or "IK_FK" not in pb.keys():
        return None
    for name in bones + ik_bones + ctrl_bones + tail_bones:
        if arm_obj.pose.bones.get(name) is None:
            return None
    base, _dot, side = bones[0].rpartition(".")
    if base.startswith("upper_arm"):
        spec["kind"], spec["side"] = "Arm", side
    elif base.startswith("thigh"):
        spec["kind"], spec["side"] = "Leg", side
    else:
        return None
    suffix = ".%s" % side
    for name in ik_bones + ctrl_bones + tail_bones + extra_ctrls:
        if not name.endswith(suffix):
            # left and right are mixed (most likely the parsing / generated script changed); better not to use it than to write the wrong side
            return None
    spec["pole_prop"] = spec.get("pole_prop") or "pole_vector"
    return spec


def _default_specs(arm_obj) -> dict:
    """Fallback when the generation script is missing (deleted / renamed): use Rigify's standard names."""
    specs: dict = {}
    for item in _DEFAULT_CHAINS.values():
        for side in ("L", "R"):
            fk_bones = [name.format(s=side) for name in item["fk"]]
            if any(arm_obj.pose.bones.get(name) is None for name in fk_bones):
                continue
            spec = {
                "prop_bone": item["parent"].format(s=side),
                "pole_prop": "pole_vector",
                "fk_bones": fk_bones,
                "ik_bones": [n.format(s=side) for n in item["ik"]],
                "ctrl_bones": [n.format(s=side) for n in item["ctrl"]],
                "tail_bones": [n.format(s=side) for n in item["tail"]],
                "extra_ctrls": [n.format(s=side) for n in item["extra"]],
                "kind": item["kind"],
                "side": side,
            }
            pb = arm_obj.pose.bones.get(spec["prop_bone"])
            if pb is None or "IK_FK" not in pb.keys():
                continue
            specs[fk_bones[0]] = spec
    return specs


def limb_specs(arm_obj) -> dict:
    """``{first FK chain bone: spec}``; returns an empty dict when the armature is not Rigify-generated.

    A spec contains prop_bone / pole_prop / fk_bones / ik_bones / ctrl_bones /
    tail_bones / extra_ctrls / kind(Arm|Leg) / side(L|R).
    """
    rid = rig_id(arm_obj)
    if not rid:
        return {}
    key = (arm_obj.name, rid)
    cached = _SPEC_CACHE.get(key)
    if cached:
        return cached

    specs: dict = {}
    body = _generated_script(rid)
    if body:
        for raw in _parse_operator_props(body, "pose.rigify_limb_ik2fk_%s" % rid):
            spec = _spec_from_raw(raw, arm_obj)
            if spec is not None:
                specs.setdefault(spec["fk_bones"][0], spec)
    if not specs:
        specs = _default_specs(arm_obj)
    if specs:
        _SPEC_CACHE[key] = specs   # never cache an empty result (the rig may still be mid-generation)
    return specs


def _limb_controls(spec: dict) -> set:
    """Names of the controls on this limb that "the user can pose directly" (Rigify's ctrl / tail / extra groups)."""
    return set(spec.get("ctrl_bones") or []) | set(spec.get("tail_bones") or []) \
        | set(spec.get("extra_ctrls") or [])


def ik_write_plan(spec: dict) -> dict | None:
    """Controls that can be written directly in IK mode; returns None when they cannot be recognised (the caller falls back to the FK path).

    Returns ``{"side", "target", "controls": {role: control bone}, "roles", "fk_of_role",
    "tip_role", "tip_fk"}``:

      * ``controls`` holds the IK bones that "match an FK role and are controls themselves" - the chain root ``upper_arm_ik.L`` /
        ``thigh_ik.L``, the end ``hand_ik.L`` / ``foot_ik.L`` (**which is the end of the IK chain**, so position + rotation are both written)
        and the tail control ``toe_ik.L``; the middle segments are decided by the IK solve and are not written;
      * ``target`` is ``*_ik_target``, which is actually the **pole target** (it decides the bend plane of the IK chain); it is only placed
        (following Rigify's ``match_pole_target``, see :func:`place_pole`) when ``pole_vector`` is enabled;
      * ``tip_role`` / ``tip_fk``: the role and FK bone of this limb's "end point" (the tail of ``forearm_fk`` is
        the wrist, the tail of ``shin_fk`` is the ankle); the direct write does not need it (it writes the control's own delta), it is kept for the self-check.
    """
    side = str(spec.get("side") or "")
    suffix = ".%s" % side
    fk_bones = list(spec.get("fk_bones") or [])
    if not side or len(fk_bones) < 2:
        return None

    target = ""
    for name in spec.get("ctrl_bones") or []:
        if name.endswith("_ik_target%s" % suffix):
            target = name
            break
    if not target:
        return None

    roles: list[str] = []
    stems: list[str] = []
    for name in fk_bones:
        if not name.endswith(suffix):
            return None
        stem = name[:-len(suffix)]
        if stem.endswith("_fk"):
            stem = stem[:-len("_fk")]
        stems.append(stem)
        roles.append("%s%s" % (stem, suffix))

    controls = _limb_controls(spec)
    writes: dict = {}
    for stem, role in zip(stems, roles):
        candidate = "%s_ik%s" % (stem, suffix)
        if candidate in controls:
            writes[role] = candidate
    if not writes:
        return None
    return {"side": side,
            "target": target,
            "controls": writes,
            "roles": roles,
            "fk_of_role": dict(zip(roles, fk_bones)),
            "tip_role": roles[1],
            "tip_fk": fk_bones[1]}


def mapped_limb_mode(arm_obj, bmap, specs: dict = None) -> str:
    """Which mode the limb bones in the mapping point to as a whole: ``"IK"`` / ``"FK"`` / ``""`` (no limbs, or cannot tell).

    Used after changing the "Limb Write Mode" to decide whether the limb bone names must be matched again: if the mapping points to FK bones but IK was selected,
    the written pose would be invisible in IK mode.
    """
    specs = specs if specs is not None else limb_specs(arm_obj)
    if not specs:
        return ""
    ik = fk = 0
    for spec in specs.values():
        plan = ik_write_plan(spec)
        roles = (plan or {}).get("roles") or []
        controls = _limb_controls(spec)
        fk_bones = set(spec.get("fk_bones") or [])
        for role in roles:
            name = bmap.get(role)
            if not name:
                continue
            if name in controls:
                ik += 1
            elif name in fk_bones:
                fk += 1
    if ik > fk:
        return MODE_IK
    if fk > ik:
        return MODE_FK
    return ""


def collection_name(spec: dict, mode: str) -> str:
    """Names of the bone collections Rigify creates for every group of controls: ``Arm.L (IK)`` / ``Leg.R (FK)``."""
    return "%s.%s (%s)" % (spec.get("kind", "?"), spec.get("side", "?"), mode)


def limb_modes(arm_obj, specs: dict = None) -> dict:
    """``{prop_bone: IK_FK}`` (IK_FK is a 0/1 float custom property, 0 = IK, 1 = FK)."""
    specs = specs if specs is not None else limb_specs(arm_obj)
    modes: dict = {}
    for spec in specs.values():
        pb = arm_obj.pose.bones.get(spec["prop_bone"])
        if pb is None or "IK_FK" not in pb.keys():
            continue
        try:
            modes[spec["prop_bone"]] = float(pb["IK_FK"])
        except (TypeError, ValueError):
            continue
    return modes


def current_mode(arm_obj, spec: dict) -> str | None:
    """Whether a single limb is currently IK or FK (returns None if the property cannot be read)."""
    pb = arm_obj.pose.bones.get(spec["prop_bone"])
    if pb is None or "IK_FK" not in pb.keys():
        return None
    try:
        return MODE_FK if float(pb["IK_FK"]) >= 0.5 else MODE_IK
    except (TypeError, ValueError):
        return None


def set_mode(arm_obj, mode: str, report: dict = None, specs: dict = None,
             sync: bool = True) -> list[str]:
    """Switch (the given) limbs to IK / FK and sync the controller visibility. Returns the prop bones that were changed."""
    specs = dict(specs) if specs is not None else limb_specs(arm_obj)
    if not specs:
        return []
    value = 1.0 if mode == MODE_FK else 0.0
    changed: list[str] = []
    for spec in specs.values():
        pb = arm_obj.pose.bones.get(spec["prop_bone"])
        if pb is None or "IK_FK" not in pb.keys():
            continue
        try:
            if abs(float(pb["IK_FK"]) - value) < 1e-6:
                continue
        except (TypeError, ValueError):
            pass
        pb["IK_FK"] = value
        changed.append(spec["prop_bone"])
    if sync:
        touched = sync_visibility(arm_obj, mode, specs)
        if report is not None and touched:
            report["visibility"] = touched
    return changed


def sync_visibility(arm_obj, mode: str = None, specs: dict = None) -> list[str]:
    """Show the group of controls that is usable for the IK/FK state and hide the other group.

    With ``mode=None`` the current ``IK_FK`` value is read limb by limb (this is what our "Sync Control Display" button uses
    after the user has dragged Rigify's slider by hand).
    """
    specs = specs if specs is not None else limb_specs(arm_obj)
    if not specs:
        return []
    # collections_all (Blender 4.1+) also contains nested bone collections; fall back to the root list on older builds
    collections = getattr(arm_obj.data, "collections_all", None) or getattr(arm_obj.data, "collections", None)
    if collections is None:
        return []
    touched: list[str] = []
    for spec in specs.values():
        limb_mode = mode or current_mode(arm_obj, spec)
        if limb_mode not in MODES:
            continue
        for tag in MODES:
            coll = collections.get(collection_name(spec, tag))
            if coll is None:
                continue
            visible = (tag == limb_mode)
            if bool(coll.is_visible) != visible:
                coll.is_visible = visible
                touched.append(coll.name)
    return touched


